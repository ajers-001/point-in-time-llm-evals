"""Production adapters: SSH hosts, presigned upload slots, status export, Lambda checks.

Host keys are generated by the controller per pod and pinned; the private
host key travels only inside the single create request. The SSH client key,
the Runpod key and the upload signer key come from Secrets Manager and are
never logged, written to durable state or sent to hosts.
"""
import base64
import inspect
import io
import json
import os
import re
import shlex
import socket
import time

from .controller import HostUnreachable

AGENT = '/pit-control/source/infra/cloud_two_gpu/host_agent.py'
SLOTS_PER_BATCH = 480  # snapshots every 120 s use ~30 per hour; renewal runs only on status calls (bootstrap), so one batch must cover a ~6 h pod plus attempts and bulk files


def host_keypair():
    """New ed25519 host key: (OpenSSH private PEM, 'ssh-ed25519 AAAA...')."""
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    key = Ed25519PrivateKey.generate()
    private = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.OpenSSH,
                                serialization.NoEncryption()).decode()
    public = key.public_key().public_bytes(serialization.Encoding.OpenSSH, serialization.PublicFormat.OpenSSH).decode()
    return private, public


def pod_startup(public_client_key_env='PUBLIC_KEY', host_key_env='SSH_HOST_ED25519_B64'):
    """sshd with key-only root login and ONLY the controller-supplied host key (base64 in env)."""
    return ('set -eu; mkdir -p /run/sshd /root/.ssh /etc/ssh; chmod 700 /root/.ssh; '
            f'printf "%s\\n" "${public_client_key_env}" > /root/.ssh/authorized_keys; chmod 600 /root/.ssh/authorized_keys; '
            f'umask 077; printf "%s" "${host_key_env}" | base64 -d > /etc/ssh/ssh_host_ed25519_key; '
            f'chmod 600 /etc/ssh/ssh_host_ed25519_key; unset {host_key_env}; '
            'exec /usr/sbin/sshd -D -e -o HostKey=/etc/ssh/ssh_host_ed25519_key -o PasswordAuthentication=no '
            '-o KbdInteractiveAuthentication=no -o PermitRootLogin=prohibit-password')


# Host driver CUDA versions a pod may have (the provider API accepts 11.8-13.0 only). The pinned stack is torch cu128,
# which runs on any 12.8+ driver. By 2026-10-26 Runpod's H200 hosts run 13.2 drivers, which no allowed value matches:
# a session may set allowed_cuda_versions to 'any' to omit the filter (the provider then accepts every host).
DEFAULT_CUDA_VERSIONS = ('12.8', '12.9', '13.0')


def build_payload(name, image, client_public_key, host_private_key, gpu_type='NVIDIA H100 80GB HBM3', disk_gb=350,
                  cuda_versions=DEFAULT_CUDA_VERSIONS, gpu_count=1):
    if '@sha256:' not in image:
        raise ValueError('Immutable image digest required')
    if cuda_versions != 'any' and (not cuda_versions or not set(cuda_versions) <= set(DEFAULT_CUDA_VERSIONS)):
        raise ValueError("CUDA host filter must be 'any' or a non-empty subset of the reviewed versions")
    if gpu_count not in (1, 2):
        raise ValueError('pods hold one or two GPUs')
    return dict(name=name, cloudType='SECURE', computeType='GPU', gpuTypeIds=[gpu_type], gpuCount=gpu_count,
                interruptible=False, imageName=image, containerDiskInGb=disk_gb, volumeInGb=0,
                minRAMPerGPU=125, minVCPUPerGPU=8,
                **({} if cuda_versions == 'any' else {'allowedCudaVersions': list(cuda_versions)}),
                ports=['22/tcp'], dockerStartCmd=['/bin/bash', '-c', pod_startup()],
                env={'PUBLIC_KEY': client_public_key,
                     'SSH_HOST_ED25519_B64': base64.b64encode(host_private_key.encode()).decode()})


class SshHosts:
    def __init__(self, client_private_key, bundle_bytes, bundle_sha, presign, timeout=60, connect=None, bulk_urls=None):
        import paramiko
        self.paramiko = paramiko
        self.pkey = paramiko.Ed25519Key.from_private_key(io.StringIO(client_private_key))
        self.bundle, self.bundle_sha, self.presign, self.bulk_urls = bundle_bytes, bundle_sha, presign, bulk_urls
        self.timeout = timeout
        self._connect = connect

    def endpoint(self, info):
        if not info or not info.get('publicIp'):
            return None
        port = (info.get('portMappings') or {}).get('22')
        return {'host': info['publicIp'], 'port': int(port)} if port else None

    def _client(self, pod, endpoint):
        public = pod.get('host_public_key')
        if not public:
            raise HostUnreachable('no pinned host key for this pod')
        kind, blob = public.split()[:2]
        client = self.paramiko.SSHClient()
        host = endpoint['host'] if endpoint['port'] == 22 else f'[{endpoint["host"]}]:{endpoint["port"]}'
        client.get_host_keys().add(host, kind, self.paramiko.PKey.from_type_string(kind, base64.b64decode(blob)))
        client.set_missing_host_key_policy(self.paramiko.RejectPolicy())
        try:
            client.connect(endpoint['host'], port=endpoint['port'], username='root', pkey=self.pkey,
                           timeout=self.timeout, banner_timeout=self.timeout, auth_timeout=self.timeout,
                           allow_agent=False, look_for_keys=False, sock=self._connect(endpoint) if self._connect else None)
        except (self.paramiko.SSHException, OSError, socket.timeout) as error:
            client.close()
            raise HostUnreachable(f'ssh {endpoint["host"]}:{endpoint["port"]}: {type(error).__name__}') from None
        return client

    def _exec(self, client, command, stdin=None, timeout=None):
        try:
            chan = client.get_transport().open_session(timeout=self.timeout)
            chan.settimeout(timeout or self.timeout)
            chan.exec_command(command)
            if stdin is not None:
                chan.sendall(stdin)
            chan.shutdown_write()  # commands never wait on interactive input
            out = io.BytesIO()
            while True:
                data = chan.recv(1 << 16)
                if not data:
                    break
                out.write(data)
            code = chan.recv_exit_status()
            return code, out.getvalue().decode(errors='replace')
        except (self.paramiko.SSHException, OSError, socket.timeout) as error:
            raise HostUnreachable(f'ssh exec failed: {type(error).__name__}') from None

    def _put(self, client, path, data, mode=0o600):
        code = ('import os,sys;from pathlib import Path;p=Path(sys.argv[1]);t=p.with_name(p.name+".partial");'
                'fd=os.open(t,os.O_WRONLY|os.O_CREAT|os.O_TRUNC,int(sys.argv[2],8));os.write(fd,sys.stdin.buffer.read());'
                'os.close(fd);os.replace(t,p)')
        rc, out = self._exec(client, f'mkdir -p /pit-control && chmod 711 /pit-control && python3 -c {shlex.quote(code)} '
                                     f'{shlex.quote(path)} {oct(mode)[2:]}', stdin=data, timeout=300)
        if rc != 0:
            raise HostUnreachable(f'upload to host failed with status {rc}')

    def provision(self, pod, endpoint, spec, epoch):
        client = self._client(pod, endpoint)
        try:
            rc, state = self._exec(client, 'test -f /pit-control/agent-state.json && echo initialised || echo new')
            if 'new' in state:
                from . import bundle as bundle_mod
                self._put(client, '/pit-control/bundle.tar.gz', self.bundle)
                extractor = inspect.getsource(bundle_mod.extract) + (
                    '\nimport hashlib,io,json,tarfile\nfrom pathlib import Path,PurePosixPath\n'
                    f'MAX_BUNDLE={bundle_mod.MAX_BUNDLE};MAX_EXPANDED={bundle_mod.MAX_EXPANDED}\n'
                    f'print(extract(Path("/pit-control/bundle.tar.gz").read_bytes(),"/pit-control/source",{self.bundle_sha!r}))')
                rc, out = self._exec(client, 'test -e /pit-control/source || python3 -c ' + shlex.quote(extractor), timeout=300)
                if rc != 0:
                    raise HostUnreachable(f'bundle verification failed on host: {out[-300:]}')
                self._put(client, '/pit-control/upload-urls.json',
                          json.dumps({'slots': self.presign(spec['pod_id'], 0, SLOTS_PER_BATCH)}).encode())
                if self.bulk_urls:  # fresh GET URLs for the frozen bulk inputs, fetched first in bootstrap
                    self._put(client, '/pit-control/bulk-urls.json', json.dumps({'urls': self.bulk_urls()}).encode())
                self._put(client, '/pit-control/spec.json', json.dumps(spec).encode())
            rc, out = self._exec(client, f'python3 {AGENT} bootstrap --epoch {int(epoch)} --spec /pit-control/spec.json')
            return self._parse(rc, out)
        finally:
            client.close()

    @staticmethod
    def _parse(rc, out):
        lines = [x for x in out.strip().splitlines() if x.strip()]
        if rc not in (0, 2) or not lines:
            raise HostUnreachable(f'host agent exited {rc}')
        return json.loads(lines[-1])

    def call(self, pod, endpoint, cmd, epoch, **kw):
        args = [AGENT, cmd, '--epoch', str(int(epoch))]
        for k, v in kw.items():
            args += ['--' + k.replace('_', '-'), str(v)]
        client = self._client(pod, endpoint)
        try:
            result = self._parse(*self._exec(client, 'python3 ' + ' '.join(shlex.quote(a) for a in args)))
            if cmd == 'status' and result.get('slots_remaining', SLOTS_PER_BATCH) < 40:
                self._renew(client, pod, epoch, result.get('slots_total', 0))
            return result
        finally:
            client.close()

    def _renew(self, client, pod, epoch, start):
        tmp = '/pit-control/new-urls.json'
        self._put(client, tmp, json.dumps({'slots': self.presign(pod['pod_id'], start, SLOTS_PER_BATCH)}).encode())
        self._exec(client, f'python3 {AGENT} install-urls --epoch {int(epoch)} --file {tmp}')

    def replace_urls(self, pod, endpoint, epoch, start):
        """Atomically replace the host's slot list with fresh URLs (keys never used before)."""
        client = self._client(pod, endpoint)
        try:
            self._exec(client, f'python3 {AGENT} fence --epoch {int(epoch)}')
            self._put(client, '/pit-control/upload-urls.json',
                      json.dumps({'slots': self.presign(pod['pod_id'], start, SLOTS_PER_BATCH)}).encode())
            return {'replaced_from_index': start, 'slots': SLOTS_PER_BATCH}
        finally:
            client.close()

    def final_backup(self, pod, endpoint, epoch):
        return self.call(pod, endpoint, 'backup-now', epoch)


class Presigner:
    """Exact-object PUT URLs signed by the append-only uploader identity."""

    def __init__(self, s3_client, bucket, session_id, expires_at, clock=time.time):
        self.s3, self.bucket, self.sid, self.expires_at, self.clock = s3_client, bucket, session_id, expires_at, clock

    def __call__(self, pod_id, start, count):
        ttl = int(min(604800, self.expires_at - self.clock()))
        if ttl < 3600:
            raise RuntimeError('upload URL lifetime would not cover the session and retrieval reserve')
        slots = []
        for i in range(start, start + count):
            key = f'sessions/{self.sid}/hosts/{pod_id}/slot-{i:04d}.tar.gz'
            url = self.s3.generate_presigned_url('put_object', ExpiresIn=ttl, HttpMethod='PUT', Params={
                'Bucket': self.bucket, 'Key': key, 'ServerSideEncryption': 'AES256', 'IfNoneMatch': '*'})
            slots.append({'key': key, 'url': url})
        return slots


class BulkGets:
    """Short-lived GET URLs for an experiment's frozen ``bulk_inputs``, signed by the controller's own role."""

    def __init__(self, s3_client, bucket, entries, ttl=3 * 3600):
        names = [e['name'] for e in entries]
        for e in entries:
            if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]{0,127}', e['name']) or '..' in e['name'] or \
                    not re.fullmatch(r'sessions/[A-Za-z0-9._/-]+', e['key']) or '..' in e['key'].split('/') or \
                    not re.fullmatch(r'[0-9a-f]{64}', e['sha256']) or type(e['bytes']) is not int or e['bytes'] <= 0:
                raise ValueError('invalid bulk input record')
        if len(set(names)) != len(names):
            raise ValueError('duplicate bulk input name')
        self.s3, self.bucket, self.entries, self.ttl = s3_client, bucket, entries, ttl

    def check(self):
        """Fail before any pod exists if an object is missing or its size differs from the frozen record."""
        for e in self.entries:
            if self.s3.head_object(Bucket=self.bucket, Key=e['key'])['ContentLength'] != e['bytes']:
                raise ValueError(f'bulk input {e["name"]} size differs from the frozen record')

    def __call__(self):
        return [{'name': e['name'], 'key': e['key'], 'url': self.s3.generate_presigned_url(
            'get_object', ExpiresIn=self.ttl, HttpMethod='GET', Params={'Bucket': self.bucket, 'Key': e['key']})}
            for e in self.entries]


def bulk_gets(s3, bucket, root, queue):
    """GET URL signer for the queue experiment's frozen bulk inputs (None when it has none); checked before any pod."""
    if not queue.get('prepared'):
        return None
    with open(os.path.join(root, queue['prepared'], 'experiment.json')) as f:
        entries = json.load(f).get('bulk_inputs') or []
    if not entries:
        return None
    bulk = BulkGets(s3, bucket, entries)
    bulk.check()
    return bulk


def status_writer(s3_client, bucket, session_id):
    def write(status):
        s3_client.put_object(Bucket=bucket, Key=f'sessions/{session_id}/status/latest.json',
                             Body=json.dumps(status, default=str, indent=2).encode(), ServerSideEncryption='AES256',
                             ContentType='application/json')
    return write


def watchdog_sees(lambda_client, function_name):
    def sees(name):
        response = lambda_client.invoke(FunctionName=function_name, InvocationType='RequestResponse',
                                        Payload=json.dumps({'dry_run': True}).encode())
        if response.get('FunctionError'):
            return False
        return name in json.loads(response['Payload'].read()).get('watched', [])
    return sees
